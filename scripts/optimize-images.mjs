/**
 * Builds responsive photo variants.
 *   source:  assets-src/photos/<name>.(png|jpg|jpeg|webp)
 *   output:  public/images/photos/<name>-<w>.(avif|webp|jpg)
 *            src/content/image-manifest.ts  (widths + intrinsic size per photo)
 *
 * Run: npm run images
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'assets-src', 'photos');
const outDir = path.join(root, 'public', 'images', 'photos');
const manifestFile = path.join(root, 'src', 'content', 'image-manifest.ts');
const WIDTHS = [400, 800, 1200];

fs.mkdirSync(outDir, { recursive: true });
const files = fs.readdirSync(srcDir).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).sort();
const manifest = {};

for (const file of files) {
  const name = file.replace(/\.[^.]+$/, '');
  const input = path.join(srcDir, file);
  const meta = await sharp(input).metadata();
  const widths = WIDTHS.filter((w) => w < meta.width).concat(Math.min(meta.width, 1600));
  const uniq = [...new Set(widths)].sort((a, b) => a - b);
  for (const w of uniq) {
    const base = sharp(input).rotate().resize({ width: w, withoutEnlargement: true });
    await base.clone().avif({ quality: 52, effort: 5 }).toFile(path.join(outDir, `${name}-${w}.avif`));
    await base.clone().webp({ quality: 76 }).toFile(path.join(outDir, `${name}-${w}.webp`));
    await base.clone().jpeg({ quality: 80, mozjpeg: true, progressive: true }).toFile(path.join(outDir, `${name}-${w}.jpg`));
  }
  manifest[name] = { widths: uniq, width: meta.width, height: meta.height };
  console.log(`${name}: ${meta.width}x${meta.height} -> ${uniq.join(', ')}`);
}

const ts = `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.
export interface PhotoEntry { widths: number[]; width: number; height: number }
export const photoManifest: Record<string, PhotoEntry> = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(manifestFile, ts);
console.log(`wrote ${Object.keys(manifest).length} photos`);
